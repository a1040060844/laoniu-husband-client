import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const repoRoot = resolve(root, "..");
const outputRoot = resolve(root, "remote-assets");
const outputAssets = resolve(outputRoot, "assets");
const localAssets = resolve(root, "src/assets");
const h5LoginFinal = resolve(repoRoot, "husband-client/src/assets/login-final");
const h5LoginSpeech = resolve(repoRoot, "husband-client/src/assets/login/speech");
const h5LoginStatic = resolve(repoRoot, "husband-client/src/assets/login");
const h5LoginStaticFiles = [
  "bg-room.png",
  "card-husband.png",
  "card-wife.png",
  "reset-button.png",
  "subtitle.png",
  "title.png",
];
const skippedExtensions = new Set([".psd", ".psb", ".psd1", ".ai"]);
const largestFiles = [];

let totalFiles = 0;
let totalBytes = 0;

function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function shouldSkipFile(path) {
  return skippedExtensions.has(extname(path).toLowerCase());
}

function recordFile(path, size) {
  const relativePath = relative(outputRoot, path).replace(/\\/g, "/");
  totalFiles += 1;
  totalBytes += size;
  largestFiles.push({ path: relativePath, bytes: size });
  largestFiles.sort((a, b) => b.bytes - a.bytes);
  if (largestFiles.length > 20) largestFiles.pop();
}

function copyTree(from, to, options = {}) {
  if (!existsSync(from)) return;

  const stats = statSync(from);
  if (stats.isDirectory()) {
    const name = from.split(/[\\/]/).at(-1);
    if (options.skipDirs?.has(name)) return;

    ensureDir(to);
    for (const entry of readdirSync(from)) {
      copyTree(join(from, entry), join(to, entry), options);
    }
    return;
  }

  if (shouldSkipFile(from)) return;
  ensureDir(resolve(to, ".."));
  copyFileSync(from, to);
  recordFile(to, stats.size);
}

function copySelectedFiles(fromDir, toDir, fileNames) {
  if (!existsSync(fromDir)) return false;
  let copiedAny = false;
  for (const fileName of fileNames) {
    const from = resolve(fromDir, fileName);
    if (!existsSync(from)) continue;
    const to = resolve(toDir, fileName);
    const stats = statSync(from);
    ensureDir(resolve(to, ".."));
    copyFileSync(from, to);
    recordFile(to, stats.size);
    copiedAny = true;
  }
  return copiedAny;
}

function formatBytes(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MiB`;
}

if (!existsSync(localAssets)) {
  console.error(`export-remote-assets: missing source directory ${localAssets}`);
  process.exit(1);
}

if (existsSync(outputRoot)) rmSync(outputRoot, { recursive: true, force: true });
ensureDir(outputAssets);

copyTree(localAssets, outputAssets, {
  skipDirs: new Set(["source", "login-final"]),
});

if (existsSync(h5LoginFinal)) {
  copyTree(h5LoginFinal, resolve(outputAssets, "login-sprites-full"));
} else {
  console.warn(`export-remote-assets: optional H5 sprite source not found: ${h5LoginFinal}`);
}

if (existsSync(h5LoginSpeech)) {
  copyTree(h5LoginSpeech, resolve(outputAssets, "login-speech-full"));
} else {
  console.warn(`export-remote-assets: optional H5 speech source not found: ${h5LoginSpeech}`);
}

if (!copySelectedFiles(h5LoginStatic, resolve(outputAssets, "login-static-full"), h5LoginStaticFiles)) {
  console.warn(`export-remote-assets: optional H5 login static source not found: ${h5LoginStatic}`);
}

const manifest = {
  version: 1,
  generatedAt: new Date().toISOString(),
  assetBasePath: "/assets",
  notes: [
    "Upload the assets directory to an HTTPS static host.",
    "Set ASSET_CONFIG.mode to remote and remoteBase to the public URL ending with /assets.",
    "login-sprites-full contains the complete H5 login-final sprite batch for future visual parity work.",
    "login-speech-full contains the H5 login speech/thought image bubbles.",
    "login-static-full contains H5 login top-level static images such as title, cards, background, and reset button.",
  ],
  totals: {
    files: totalFiles,
    bytes: totalBytes,
    humanBytes: formatBytes(totalBytes),
  },
  largestFiles,
};

writeFileSync(resolve(outputRoot, "asset-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
writeFileSync(
  resolve(outputRoot, "README.md"),
  [
    "# Remote Assets Export",
    "",
    "This directory is generated by `npm run export:remote-assets`.",
    "",
    "Upload `assets/` to an HTTPS static host or CDN. If the uploaded URL is:",
    "",
    "`https://static.example.com/laoniu/assets`",
    "",
    "then configure `src/config/assets.ts` like this:",
    "",
    "```ts",
    "export const ASSET_CONFIG = {",
    '  mode: "remote",',
    '  localBase: "/assets",',
    '  remoteBase: "https://static.example.com/laoniu/assets",',
    "};",
    "```",
    "",
    "The generated `asset-manifest.json` lists total size and the largest files.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`export-remote-assets: wrote ${totalFiles} files, ${formatBytes(totalBytes)} -> ${outputRoot}`);
